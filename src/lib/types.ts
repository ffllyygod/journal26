export type Track = 'career' | 'trading' | 'personal';
export type HabitStatus = 'unset' | 'kept' | 'slip';
export type View = 'today' | 'journal' | 'trades' | 'career' | 'review' | 'settings';
export type Attachment = { id: string; name: string; path: string; mime: string; size: number };
export type Task = { id: string; title: string; track: Track; minutes: number; done: boolean };
export type DayEntry = {
  priorities: string[];
  tasks: Task[];
  journal: string;
  win: string;
  lesson: string;
  mood: number | null;
  careerMinutes: number;
  tradingMinutes: number;
  smoking: HabitStatus;
  abstinence: HabitStatus;
  trigger: string;
  noTrade: boolean;
  noTradeReason: string;
  attachments: Attachment[];
};
export type Trade = {
  id: string;
  date: string;
  symbol: 'XAUUSD' | 'BTC' | 'ETH';
  account: 'demo' | 'live';
  direction: 'long' | 'short';
  status: 'open' | 'closed';
  setup: string;
  entry: number;
  exit: number | null;
  stop: number | null;
  target: number | null;
  size: string;
  risk: number | null;
  netPnl: number | null;
  fees: number;
  emotion: string;
  followedPlan: 'yes' | 'no' | 'unset';
  thesis: string;
  review: string;
  attachments: Attachment[];
};
export type Application = {
  id: string;
  company: string;
  role: string;
  url: string;
  status: 'saved' | 'applied' | 'interview' | 'offer' | 'closed';
  appliedOn: string;
  followUp: string;
  notes: string;
};
export type LearningNote = { id: string; date: string; topic: string; notes: string; url: string };
export type Settings = {
  name: string;
  startDate: string;
  duration: number;
  timezone: string;
  careerTarget: number;
  tradingTarget: number;
  currency: string;
  intention: string;
  configured: boolean;
};
export type Workspace = {
  version: 1;
  settings: Settings;
  days: Record<string, DayEntry>;
  trades: Trade[];
  applications: Application[];
  learning: LearningNote[];
  weeklyNotes: Record<string, string>;
};
export type UpdateWorkspace = (updater: (current: Workspace) => Workspace) => void;
export type FeatureProps = { data: Workspace; update: UpdateWorkspace; date: string; demo: boolean; userId?: string };
